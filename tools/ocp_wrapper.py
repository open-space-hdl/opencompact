"""VHDL top level with the generics of a configuration of tools/ocp_configs.py, for synthesis.

The wrapper `ocp_synth_top` instantiates ocp_core with the generics of the configuration as constants (vector
generics as aggregates), so that synthesis tools that cannot set array generics from the command line elaborate the
core of that configuration.
"""

import ocp_generics

VECTORS = {"WeightExpOffsets_g", "WeightInitValues_g", "AbsErrorLimits_g", "RelErrorLimits_g", "Damping_g",
           "Offset_g", "AccuInit_g", "HybridAccuInit_g", "HybridAccuInitHigh_g"}
STRINGS = {"EncodingOrder_g", "EntropyCoder_g", "PredictionMode_g", "LocalSum_g", "Fidelity_g", "RamStyle_g"}


def value(name, val):
    if name in VECTORS:
        items = [v.strip() for v in str(val).split(",")]
        if len(items) == 1:
            return "(0 => {})".format(items[0])
        return "({})".format(", ".join(items))
    if name in STRINGS:
        return '"{}"'.format(val)
    if name == "SupTableData_g":
        return 'x"{}"'.format(val)
    if isinstance(val, bool):
        return "true" if val else "false"
    return str(val)


# Width of the compressed image interface of the synthesis top level
OUT_WIDTH = 32


def wrapper(cfg, name="ocp_synth_top", out_width=OUT_WIDTH, use_in_last=False, extra=None):
    """use_in_last: image framing with In_Last (UseInLast_g); extra: further generics of ocp_core (for example
    Speculation_g or RamStyle_g), which replace those of the configuration."""
    gen = ocp_generics.generics(cfg)
    gen["OutWidth_g"] = out_width
    gen["UseInLast_g"] = use_in_last
    gen.update(extra or {})
    d = gen["DynamicRange_g"]
    maps = ",\n".join("            {} => {}".format(k, value(k, v)) for k, v in gen.items())
    return """-- Synthesis top level of one OpenCompact configuration (generated by tools/ocp_wrapper.py)
library ieee;
    use ieee.std_logic_1164.all;

library opencompact;

entity {name} is
    port (
        Clk            : in    std_logic;
        Rst            : in    std_logic;
        In_Valid       : in    std_logic;
        In_Ready       : out   std_logic;
        In_Data        : in    std_logic_vector({dm1} downto 0);
        In_Last        : in    std_logic;
        In_Error       : in    std_logic;
        Lim_Valid      : in    std_logic;
        Lim_Ready      : out   std_logic;
        Lim_Data       : in    std_logic_vector(15 downto 0);
        Out_Valid      : out   std_logic;
        Out_Ready      : in    std_logic;
        Out_Data       : out   std_logic_vector({owm1} downto 0);
        Out_Keep       : out   std_logic_vector({okm1} downto 0);
        Out_Last       : out   std_logic;
        Out_Error      : out   std_logic;
        Ecc_Sec        : out   std_logic;
        Ecc_Ded        : out   std_logic;
        Ev_ImageError  : out   std_logic;
        ErrInj_Channel : in    std_logic_vector(3 downto 0);
        ErrInj_Double  : in    std_logic;
        ErrInj_Valid   : in    std_logic
    );
end entity;

architecture rtl of {name} is
begin

    i_core : entity opencompact.ocp_core
        generic map (
{maps}
        )
        port map (
            Clk            => Clk,
            Rst            => Rst,
            In_Valid       => In_Valid,
            In_Ready       => In_Ready,
            In_Data        => In_Data,
            In_Last        => In_Last,
            In_Error       => In_Error,
            Lim_Valid      => Lim_Valid,
            Lim_Ready      => Lim_Ready,
            Lim_Data       => Lim_Data,
            Out_Valid      => Out_Valid,
            Out_Ready      => Out_Ready,
            Out_Data       => Out_Data,
            Out_Keep       => Out_Keep,
            Out_Last       => Out_Last,
            Out_Error      => Out_Error,
            Ecc_Sec        => Ecc_Sec,
            Ecc_Ded        => Ecc_Ded,
            Ev_ImageError  => Ev_ImageError,
            ErrInj_Channel => ErrInj_Channel,
            ErrInj_Double  => ErrInj_Double,
            ErrInj_Valid   => ErrInj_Valid
        );

end architecture;
""".format(name=name, dm1=d - 1, maps=maps, owm1=out_width - 1, okm1=out_width // 8 - 1)
