"""VHDL top level with the generics of a configuration of tools/ocp_configs.py, for synthesis.

The wrapper `ocp_synth_top` instantiates ocp_core with the generics of the configuration as constants (vector
generics as aggregates), so that synthesis tools that cannot set array generics from the command line elaborate the
core of that configuration.
"""

import ocp_generics

VECTORS = {"WeightExpOffsets_g", "WeightInitValues_g", "AbsErrorLimits_g", "RelErrorLimits_g", "Damping_g",
           "Offset_g", "AccuInit_g", "HybridAccuInit_g", "HybridAccuInitHigh_g"}
STRINGS = {"EncodingOrder_g", "EntropyCoder_g", "PredictionMode_g", "LocalSum_g", "Fidelity_g"}


def value(name, val):
    if name in VECTORS:
        items = [v.strip() for v in str(val).split(",")]
        if len(items) == 1:
            return "(0 => {})".format(items[0])
        return "({})".format(", ".join(items))
    if name in STRINGS:
        return '"{}"'.format(val)
    if name == "SupTableData_g":
        return 'x"{}"'.format(val)
    if isinstance(val, bool):
        return "true" if val else "false"
    return str(val)


def wrapper(cfg, name="ocp_synth_top"):
    gen = ocp_generics.generics(cfg)
    d = gen["DynamicRange_g"]
    maps = ",\n".join("            {} => {}".format(k, value(k, v)) for k, v in gen.items())
    return """-- Synthesis top level of one OpenCompact configuration (generated by tools/ocp_wrapper.py)
library ieee;
    use ieee.std_logic_1164.all;

library opencompact;

entity {name} is
    port (
        Clk       : in    std_logic;
        Rst       : in    std_logic;
        In_Valid  : in    std_logic;
        In_Ready  : out   std_logic;
        In_Data   : in    std_logic_vector({dm1} downto 0);
        Lim_Valid : in    std_logic;
        Lim_Ready : out   std_logic;
        Lim_Data  : in    std_logic_vector(15 downto 0);
        Out_Valid : out   std_logic;
        Out_Ready : in    std_logic;
        Out_Data  : out   std_logic_vector(7 downto 0);
        Out_Last  : out   std_logic;
        Ecc_Sec   : out   std_logic;
        Ecc_Ded   : out   std_logic
    );
end entity;

architecture rtl of {name} is
begin

    i_core : entity opencompact.ocp_core
        generic map (
{maps}
        )
        port map (
            Clk       => Clk,
            Rst       => Rst,
            In_Valid  => In_Valid,
            In_Ready  => In_Ready,
            In_Data   => In_Data,
            Lim_Valid => Lim_Valid,
            Lim_Ready => Lim_Ready,
            Lim_Data  => Lim_Data,
            Out_Valid => Out_Valid,
            Out_Ready => Out_Ready,
            Out_Data  => Out_Data,
            Out_Last  => Out_Last,
            Ecc_Sec   => Ecc_Sec,
            Ecc_Ded   => Ecc_Ded
        );

end architecture;
""".format(name=name, dm1=d - 1, maps=maps)
